struct Table {
    const TagInfo* data;
    std::size_t size;
};

Table tableFor(IfdKind kind, const char* maker) {
    switch (kind) {
        case IfdKind::Ifd1: return {kIfd1, sizeof(kIfd1) / sizeof(kIfd1[0])};
        case IfdKind::Exif: return {kExif, sizeof(kExif) / sizeof(kExif[0])};
        case IfdKind::Interop: return {kInterop, sizeof(kInterop) / sizeof(kInterop[0])};
        case IfdKind::Gps: return {kGps, sizeof(kGps) / sizeof(kGps[0])};
        case IfdKind::MakerNote: {
            const std::string m = maker ? toLower(maker) : std::string();
            if (m.find("nikon") != std::string::npos) return {kNikon, sizeof(kNikon) / sizeof(kNikon[0])};
            if (m.find("canon") != std::string::npos) return {kCanon, sizeof(kCanon) / sizeof(kCanon[0])};
            if (m.find("apple") != std::string::npos) return {kApple, sizeof(kApple) / sizeof(kApple[0])};
            if (m.find("fuji") != std::string::npos) return {kFuji, sizeof(kFuji) / sizeof(kFuji[0])};
            if (m.find("sony") != std::string::npos) return {kSony, sizeof(kSony) / sizeof(kSony[0])};
            if (m.find("olympus") != std::string::npos || m.find("om digital") != std::string::npos)
                return {kOlympus, sizeof(kOlympus) / sizeof(kOlympus[0])};
            if (m.find("panasonic") != std::string::npos || m.find("leica camera") != std::string::npos)
                return {kPanasonic, sizeof(kPanasonic) / sizeof(kPanasonic[0])};
            if (m.find("pentax") != std::string::npos || m.find("ricoh") != std::string::npos)
                return {kPentax, sizeof(kPentax) / sizeof(kPentax[0])};
            if (m.find("samsung") != std::string::npos) return {kSamsung, sizeof(kSamsung) / sizeof(kSamsung[0])};
            if (m.find("leica") != std::string::npos) return {kLeica, sizeof(kLeica) / sizeof(kLeica[0])};
            if (m.find("google") != std::string::npos) return {kGoogle, sizeof(kGoogle) / sizeof(kGoogle[0])};
            if (m.find("dji") != std::string::npos) return {kDji, sizeof(kDji) / sizeof(kDji[0])};
            return {nullptr, 0};
        }
        default: return {kIfd0, sizeof(kIfd0) / sizeof(kIfd0[0])};
    }
}

// Tag tables are compiled-in constants; build a hash index once and verify
// that each table really is sorted (a build-time invariant we can check at
// runtime for free on first use).
using Index = std::unordered_map<std::uint16_t, const TagInfo*>;

// The cache is a deque rather than a vector on purpose: indexFor() hands out a
// reference into it, and the caller keeps using that reference after the lock
// has been released (see lookupTag() below). push_back on a deque never
// invalidates references to existing elements, while a vector reallocation
// would leave every earlier caller holding a dangling reference as soon as one
// more table is indexed. Do not "simplify" this back to a vector.
const Index& indexFor(Table t) {
    static std::mutex mu;
    static std::deque<std::pair<const TagInfo*, Index>> cache;
    std::lock_guard<std::mutex> lock(mu);
    for (const auto& entry : cache) {
        if (entry.first == t.data) return entry.second;
    }
    Index idx;
    idx.reserve(t.size * 2);
    for (std::size_t i = 0; i < t.size; ++i) {
        idx.emplace(t.data[i].id, &t.data[i]);
    }
    cache.emplace_back(t.data, std::move(idx));
    return cache.back().second;
}

const TagInfo* lookupTag(IfdKind kind, const char* maker, std::uint16_t id) {
    const Table t = tableFor(kind, maker);
    if (!t.data || t.size == 0) return nullptr;
    const Index& idx = indexFor(t);
    const auto it = idx.find(id);
    return it == idx.end() ? nullptr : it->second;
}

IfdKind makerNoteKind(const char*) { return IfdKind::MakerNote; }

const TagInfo* tagTableFor(IfdKind kind, const char* maker, std::size_t& count) {
    const Table t = tableFor(kind, maker);
    count = t.size;
    return t.data;
}

